-- 06_governance.sql
-- Who sees what. Homeowner names and street numbers are personal data;
-- an analyst sizing a program doesn't need them. And each territory team
-- should only see its own state.

USE ROLE ACME_ENGINEER;
USE WAREHOUSE ACME_EE_WH;
USE SCHEMA ACME_EE.CORE;

-- Which role covers which state. A table, not hard-coded logic, so
-- reassigning territory is an INSERT, not a policy change.
CREATE TABLE IF NOT EXISTS TERRITORY_ACCESS (role_name STRING, state STRING);
MERGE INTO TERRITORY_ACCESS t
USING (SELECT * FROM VALUES ('ACME_ANALYST','MA'),
                            ('ACME_PROGRAM_MGR','MA'), ('ACME_PROGRAM_MGR','CT')) s(role_name, state)
ON t.role_name = s.role_name AND t.state = s.state
WHEN NOT MATCHED THEN INSERT VALUES (s.role_name, s.state);

CREATE OR REPLACE MASKING POLICY MASK_OWNER AS (v STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('ACME_PROGRAM_MGR') OR IS_ROLE_IN_SESSION('ACME_ENGINEER') THEN v
       ELSE '*** redacted ***' END;

-- Analysts keep the street (useful for mapping a neighborhood), lose the house number.
CREATE OR REPLACE MASKING POLICY MASK_ADDRESS AS (v STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('ACME_PROGRAM_MGR') OR IS_ROLE_IN_SESSION('ACME_ENGINEER') THEN v
       ELSE REGEXP_REPLACE(v, '^[0-9]+[A-Za-z]?\\s+', '### ') END;

CREATE OR REPLACE ROW ACCESS POLICY BY_TERRITORY AS (municipality STRING) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('ACME_ENGINEER')
  OR EXISTS (SELECT 1 FROM ACME_EE.CORE.TERRITORY_ACCESS a
             WHERE IS_ROLE_IN_SESSION(a.role_name)
               AND a.state = TRIM(SPLIT_PART(municipality, ',', 2)));

ALTER TABLE PROPERTY_ASSESSMENTS MODIFY COLUMN owner_name SET MASKING POLICY MASK_OWNER;
ALTER TABLE PROPERTY_ASSESSMENTS MODIFY COLUMN address    SET MASKING POLICY MASK_ADDRESS;
ALTER TABLE PROPERTY_ASSESSMENTS ADD ROW ACCESS POLICY BY_TERRITORY ON (municipality);

-- Read access for the business roles. Views over PROPERTY_ASSESSMENTS
-- (like PROGRAM_RECOMMENDATIONS) inherit the masking and row policies.
GRANT USAGE ON DATABASE ACME_EE TO ROLE ACME_ANALYST;
GRANT USAGE ON DATABASE ACME_EE TO ROLE ACME_PROGRAM_MGR;
GRANT USAGE ON SCHEMA ACME_EE.CORE TO ROLE ACME_ANALYST;
GRANT USAGE ON SCHEMA ACME_EE.CORE TO ROLE ACME_PROGRAM_MGR;
GRANT USAGE ON SCHEMA ACME_EE.APP  TO ROLE ACME_PROGRAM_MGR;
GRANT SELECT ON TABLE PROPERTY_ASSESSMENTS     TO ROLE ACME_ANALYST;
GRANT SELECT ON TABLE PROPERTY_ASSESSMENTS     TO ROLE ACME_PROGRAM_MGR;
GRANT SELECT ON VIEW  PROGRAM_RECOMMENDATIONS  TO ROLE ACME_ANALYST;
GRANT SELECT ON VIEW  PROGRAM_RECOMMENDATIONS  TO ROLE ACME_PROGRAM_MGR;
GRANT SELECT ON TABLE DEEMED_SAVINGS           TO ROLE ACME_ANALYST;
GRANT SELECT ON TABLE DEEMED_SAVINGS           TO ROLE ACME_PROGRAM_MGR;
GRANT SELECT, UPDATE ON TABLE REVIEW_QUEUE     TO ROLE ACME_PROGRAM_MGR;
-- Lets the app apply saved corrections without giving the role write access to the table.
GRANT USAGE ON PROCEDURE REFRESH_PROPERTIES()  TO ROLE ACME_PROGRAM_MGR;
GRANT SELECT, UPDATE ON TABLE OUTREACH_DRAFTS  TO ROLE ACME_PROGRAM_MGR;
GRANT USAGE ON WAREHOUSE ACME_EE_WH TO ROLE ACME_ANALYST;
GRANT USAGE ON WAREHOUSE ACME_EE_WH TO ROLE ACME_PROGRAM_MGR;

