-- 00_setup.sql
-- Database, schemas, warehouse and the three roles used throughout the demo.
-- Run as ACCOUNTADMIN. Safe to re-run.

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS ACME_EE;
CREATE SCHEMA IF NOT EXISTS ACME_EE.RAW;    -- staged files, parse and extract output
CREATE SCHEMA IF NOT EXISTS ACME_EE.CORE;   -- clean property table, scoring, policies
CREATE SCHEMA IF NOT EXISTS ACME_EE.APP;    -- semantic view, agent, Streamlit

CREATE WAREHOUSE IF NOT EXISTS ACME_EE_WH
  WAREHOUSE_SIZE = XSMALL     -- AI functions don't run faster on bigger warehouses
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- Roles
CREATE ROLE IF NOT EXISTS ACME_ENGINEER;     -- builds and runs the pipeline, sees PII
CREATE ROLE IF NOT EXISTS ACME_ANALYST;      -- read-only, PII masked
CREATE ROLE IF NOT EXISTS ACME_PROGRAM_MGR;  -- agent + app, own territory only, PII masked

GRANT ROLE ACME_ENGINEER    TO ROLE SYSADMIN;
GRANT ROLE ACME_ANALYST     TO ROLE ACME_ENGINEER;
GRANT ROLE ACME_PROGRAM_MGR TO ROLE ACME_ENGINEER;

SET me = CURRENT_USER();
GRANT ROLE ACME_ENGINEER    TO USER IDENTIFIER($me);
GRANT ROLE ACME_ANALYST     TO USER IDENTIFIER($me);
GRANT ROLE ACME_PROGRAM_MGR TO USER IDENTIFIER($me);

-- Two separate gates protect Cortex AI functions:
--   1. the SNOWFLAKE.CORTEX_USER database role
--   2. the account-level USE AI FUNCTIONS privilege
-- Many accounts grant both to PUBLIC by default. Ours didn't, and the error you get
-- ("Unknown function AI_EXTRACT") doesn't make that obvious. Grant only what each role needs.
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACME_ENGINEER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ACME_PROGRAM_MGR;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE ACME_ENGINEER;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE ACME_PROGRAM_MGR;

-- Object access
GRANT USAGE ON WAREHOUSE ACME_EE_WH TO ROLE ACME_ENGINEER;
GRANT USAGE ON WAREHOUSE ACME_EE_WH TO ROLE ACME_ANALYST;
GRANT USAGE ON WAREHOUSE ACME_EE_WH TO ROLE ACME_PROGRAM_MGR;

GRANT OWNERSHIP ON SCHEMA ACME_EE.RAW  TO ROLE ACME_ENGINEER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ACME_EE.CORE TO ROLE ACME_ENGINEER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA ACME_EE.APP  TO ROLE ACME_ENGINEER COPY CURRENT GRANTS;
GRANT USAGE ON DATABASE ACME_EE TO ROLE ACME_ENGINEER;
GRANT USAGE ON DATABASE ACME_EE TO ROLE ACME_ANALYST;
GRANT USAGE ON DATABASE ACME_EE TO ROLE ACME_PROGRAM_MGR;

-- Tasks need this to run on a schedule
GRANT EXECUTE TASK ON ACCOUNT TO ROLE ACME_ENGINEER;
